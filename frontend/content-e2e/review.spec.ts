import { test, expect } from '@playwright/test'

test('真实 Review：五种卡片、评分、幂等重试、刷新、撤销、录音上传和简单设置', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await context.grantPermissions(['microphone'])
  const unique = Date.now()
  await page.goto('/login')
  await page.getByRole('button', { name: '没有账号？创建账号' }).click()
  await page.getByLabel('邮箱').fill(`review-${unique}@example.invalid`)
  await page.getByLabel('密码', { exact: true }).fill('Review-integration-2026-password')
  await page.getByRole('button', { name: '创建并登录' }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await page.goto('/library')
  await expect(page.getByRole('heading', { name: '题库资源', exact: true })).toBeVisible()
  const api = async (method: string, path: string, body?: unknown) => page.evaluate(async ({ method, path, body }) => {
    const csrf = await fetch('/api/content/v1/auth/csrf').then(r => r.json())
    const response = await fetch('/api/content/v1' + path, { method, headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': csrf.csrf_token }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) })
    const data = await response.json()
    if (!response.ok) throw new Error(`${response.status}: ${JSON.stringify(data)}`)
    return data
  }, { method, path, body })
  const newDeck = async (name: string) => (await api('POST', '/decks', { name: `${name} ${unique}` })).id as string
  const note = async (deckId: string, template: string, fields: Record<string, string>) => api('POST', '/notes', { deck_id: deckId, note_type_key: template.startsWith('vocabulary') ? 'vocabulary' : 'sentence', card_template_key: template, fields })
  const vocab = await newDeck('单词复习')
  await note(vocab, 'vocabulary_english_to_chinese', { word: 'journey', meaning: '旅程', mnemonic: '记忆联想' })
  await page.goto(`/review/${vocab}`)
  await expect(page.getByText('journey', { exact: true })).toBeVisible()
  await expect(page.getByText('记忆联想', { exact: true })).toHaveCount(0)
  const frontResponse = await page.request.get('/api/content/v1/review/deck-counts')
  expect(frontResponse.ok()).toBeTruthy()
  await page.getByRole('button', { name: '显示答案', exact: true }).click()
  await expect(page.getByTestId('rate-good')).toBeEnabled()
  await expect(page.getByText('记忆联想', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('记忆联想', { exact: true })).toBeVisible()
  // Again schedules 15 minutes ahead; with no other work, learn ahead now.
  await page.getByTestId('rate-again').click()
  await expect(page.getByRole('button', { name: '显示答案', exact: true })).toBeVisible()
  await expect(page.getByText('journey', { exact: true })).toBeVisible()
  await expect(page.getByText('记忆联想', { exact: true })).toHaveCount(0)
  await expect(page.getByTestId('review-empty')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: '显示答案', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '显示答案', exact: true }).click()
  await expect(page.getByText('记忆联想', { exact: true })).toBeVisible()
  const keys: string[] = []
  let failResponse = true
  await page.route('**/review/queues/*/attempts/*/rating', async route => {
    keys.push(route.request().headers()['idempotency-key'] || '')
    const response = await route.fetch()
    if (failResponse) { failResponse = false; await route.abort('connectionreset') }
    else await route.fulfill({ response })
  })
  await page.getByTestId('rate-easy').click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.getByTestId('review-empty')).toBeVisible()
  expect(keys).toHaveLength(2)
  expect(keys[0]).toBe(keys[1])
  await page.unroute('**/review/queues/*/attempts/*/rating')
  await page.getByRole('button', { name: '撤回上一张', exact: true }).click()
  await expect(page.getByTestId('rate-good')).toBeEnabled()
  await expect(page.getByText('记忆联想', { exact: true })).toBeVisible()
  await page.getByTestId('rate-easy').click()
  await expect(page.getByTestId('review-empty')).toBeVisible()
  await page.goto(`/settings?deck_id=${vocab}`)
  await expect(page.getByLabel('每日新学数量')).toBeVisible()
  await expect(page.getByLabel('学习步长（分钟）', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('最大复习间隔（天）')).toHaveCount(0)
  await page.getByLabel('每日新学数量').fill('5')
  const saved = page.waitForResponse(response => response.url().includes('/settings') && response.request().method() === 'PUT')
  await page.getByRole('button', { name: '保存设置' }).click()
  expect((await saved).ok()).toBeTruthy()
  await page.reload()
  await expect(page.getByLabel('每日新学数量')).toHaveValue('5')

  const reverse = await newDeck('中译英')
  await note(reverse, 'vocabulary_chinese_to_english', { word: 'apple', meaning: '苹果' })
  await page.goto(`/review/${reverse}`)
  await expect(page.getByText('苹果', { exact: true })).toBeVisible()
  await expect(page.getByText('apple', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '暂停此卡', exact: true }).click()
  await expect(page.getByTestId('review-empty')).toBeVisible()
  await page.getByRole('button', { name: '暂停/跳过', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '恢复', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('没有暂停或跳过的卡片。')).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click()
  await expect(page.getByText('苹果', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '显示答案', exact: true }).click()
  await expect(page.getByText('apple', { exact: true })).toBeVisible()
  await page.getByTestId('rate-easy').click()
  await expect(page.getByTestId('review-empty')).toBeVisible()

  const text = await newDeck('翻译')
  await note(text, 'sentence_translation', { english: 'Hello, world!', chinese: '你好，世界！' })
  await page.goto(`/review/${text}`)
  await page.getByRole('textbox', { name: '我的译文' }).fill('  Hi, world!  ')
  await page.getByRole('button', { name: '显示答案', exact: true }).click()
  await expect(page.getByText('Hello, world!', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Hi, world!', { exact: false })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByTestId('rate-good')).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '/tmp/langear-review-mobile.png' })
  await page.getByTestId('rate-easy').click()
  await expect(page.getByTestId('review-empty')).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: '撤回上一张', exact: true }).click()
  await expect(page.getByTestId('transcript-row')).toContainText('Hi, world!')
  await page.reload()
  await expect(page.getByTestId('rate-good')).toBeEnabled()
  await page.getByTestId('rate-easy').click()
  await expect(page.getByTestId('review-empty')).toBeVisible()

  // Create one owned reference recording through the actual OSS upload/verification API.
  const uploaded = await page.evaluate(async () => {
    const stream = await navigator.mediaDevices.getUserMedia({ audio: true })
    const chunks: BlobPart[] = []
    const recorder = new MediaRecorder(stream, { mimeType: 'audio/webm' })
    const done = new Promise<Blob>(resolve => {
      recorder.ondataavailable = event => chunks.push(event.data)
      recorder.onstop = () => { stream.getTracks().forEach(track => track.stop()); resolve(new Blob(chunks, { type: 'audio/webm' })) }
    })
    recorder.start()
    await new Promise(resolve => setTimeout(resolve, 700))
    recorder.stop()
    const blob = await done
    const csrf = await fetch('/api/content/v1/auth/csrf').then(r => r.json())
    const grantResponse = await fetch('/api/content/v1/media-assets/audio-uploads', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': csrf.csrf_token }, body: JSON.stringify({ content_type: 'audio/webm', size_bytes: blob.size }) })
    const grant = await grantResponse.json()
    if (!grantResponse.ok) throw new Error(`Grant failed: ${JSON.stringify(grant)}`)
    const put = await fetch(grant.upload_url, { method: 'PUT', headers: grant.headers, body: blob })
    if (!put.ok) throw new Error(`OSS upload failed: ${put.status}`)
    const response = await fetch(`/api/content/v1/media-assets/${grant.media_asset_id}/confirm-upload`, { method: 'POST', headers: { 'X-CSRF-Token': csrf.csrf_token } })
    if (!response.ok) throw new Error(`Confirm failed: ${response.status}`)
    return grant.media_asset_id as string
  })
  expect(uploaded).toMatch(/^[0-9a-f-]{36}$/)
  const media = await api('GET', '/media-assets?limit=500')
  const reference = media.media_assets.find((asset: { kind: string }) => asset.kind === 'audio')?.id
  expect(reference, 'The isolated staging copy must contain a ready shared reference audio').toBeTruthy()
  const recording = await newDeck('复述')
  await note(recording, 'sentence_retelling', { english: 'Hello, world!', reference_audio: reference })
  await page.goto(`/review/${recording}`)
  await page.setViewportSize({ width: 390, height: 844 })
  const remaining = page.getByRole('status', { name: '剩余卡片' })
  await expect(remaining.locator('dd')).toHaveText(['1', '0', '0'])
  for (const label of ['未学习', '学习中', '待复习']) {
    await expect(remaining.getByText(label, { exact: true })).toBeInViewport()
  }
  await expect(page.getByTestId('flip-button')).toBeDisabled()
  await page.getByTestId('record-toggle').click()
  await expect(page.getByTestId('record-toggle')).toContainText('停止')
  await expect(remaining).toBeInViewport()
  await page.waitForTimeout(700)
  await page.getByTestId('record-toggle').click()
  await expect(page.getByTestId('flip-button')).toBeEnabled()
  await page.getByTestId('flip-button').click()
  await expect(page.getByTestId('rate-good')).toBeEnabled()
  await expect(page.getByTestId('transcription-result')).toBeVisible()
  await expect(remaining).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '/tmp/langear-retelling-counts-mobile.png' })
  await page.reload()
  await expect(page.getByTestId('rate-good')).toBeEnabled()
  await expect(page.locator('audio').last()).toHaveAttribute('src', /^https:/)
  await page.getByTestId('rate-easy').click()
  await expect(page.getByTestId('review-empty')).toBeVisible()
  await expect(remaining.locator('dd')).toHaveText(['0', '0', '0'])
  await page.getByRole('button', { name: '撤回上一张', exact: true }).click()
  await expect(page.getByTestId('card-back-container')).toBeVisible()
  await expect(page.getByTestId('original-text')).toContainText(/Hello,\s*world!/)
  await expect(page.getByTestId('rate-good')).toBeEnabled()
  await page.getByTestId('rate-easy').click()
  await expect(page.getByTestId('review-empty')).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1000 })

  const dictation = await newDeck('听写')
  await note(dictation, 'sentence_dictation', { english: '“Hello”', reference_audio: reference })
  await page.goto(`/review/${dictation}`)
  await expect(page.getByText('“Hello”', { exact: true })).toHaveCount(0)
  await page.getByRole('textbox', { name: '我的听写' }).fill('"Hello"')
  await page.getByRole('button', { name: '显示答案', exact: true }).click()
  await expect(page.getByTestId('text-difference-count')).toHaveText('0 处差异')
  await page.getByTestId('rate-easy').click()
  await expect(page.getByTestId('review-empty')).toBeVisible()
  await page.getByRole('button', { name: '撤回上一张', exact: true }).click()
  await expect(page.getByTestId('transcript-row')).toContainText('"Hello"')
  await expect(page.getByTestId('text-difference-count')).toHaveText('0 处差异')
  await page.getByTestId('rate-easy').click()
  await expect(page.getByTestId('review-empty')).toBeVisible()

  // Undo from the next card's front restores the previous back and schedule.
  const twoCards = await newDeck('撤回上一张')
  await note(twoCards, 'vocabulary_english_to_chinese', { word: 'first', meaning: '第一张答案' })
  await note(twoCards, 'vocabulary_english_to_chinese', { word: 'second', meaning: '第二张答案' })
  await page.goto(`/review/${twoCards}`)
  await expect(page.getByTestId('card-front-container')).toBeVisible()
  const firstWord = (await page.getByTestId('card-front-container').innerText()).trim()
  expect(['first', 'second']).toContain(firstWord)
  const nextWord = firstWord === 'first' ? 'second' : 'first'
  await page.getByRole('button', { name: '显示答案', exact: true }).click()
  await page.getByTestId('rate-easy').click()
  await expect(page.getByText(nextWord, { exact: true })).toBeVisible()
  await page.getByRole('group', { name: '卡片操作' }).getByRole('button', { name: '撤回上一张' }).click()
  await expect(page.getByText(firstWord, { exact: true })).toBeVisible()
  await expect(page.getByText(firstWord === 'first' ? '第一张答案' : '第二张答案', { exact: true })).toBeVisible()
  await page.getByTestId('rate-easy').click()
  await expect(page.getByText(nextWord, { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
