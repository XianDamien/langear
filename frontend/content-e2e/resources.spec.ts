import { test, expect } from '@playwright/test'

test('创建牌组、混合添加卡片、刷新持久化和移动端表单', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const suffix = Date.now()
  const deck = `浏览器验收 ${suffix}`
  await page.goto('/login')
  await page.getByRole('button', { name: '没有账号？创建账号' }).click()
  await page.getByLabel('邮箱').fill(`resource-e2e-${suffix}@example.invalid`)
  await page.getByLabel('密码', { exact: true }).fill('Resource-browser-check-2026')
  await page.getByRole('button', { name: '创建并登录' }).click()
  await expect(page.getByRole('heading', { name: '题库资源' })).toBeVisible()
  await page.getByRole('button', { name: '添加牌组', exact: true }).first().click()
  let dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('combobox')).toHaveCount(0)
  await dialog.getByLabel('新牌组名称').fill(deck)
  await dialog.getByRole('button', { name: '添加', exact: true }).click()
  await expect(page.getByRole('heading', { name: deck, exact: true })).toBeVisible()
  await page.getByRole('button', { name: '添加卡片', exact: true }).first().click()
  dialog = page.getByRole('dialog')
  const deckId = await dialog.getByLabel('归属牌组').inputValue()
  expect(deckId).toBeTruthy()
  await dialog.getByLabel('单词', { exact: false }).fill('journey')
  await dialog.getByLabel('释义', { exact: false }).fill('旅程')
  await expect(dialog.locator('.template-chip')).toHaveText(['英译中', '中译英'])
  await dialog.getByLabel('卡片类型').selectOption('sentence')
  await dialog.getByLabel('英文', { exact: false }).fill('Every journey begins with a single step.')
  await dialog.getByLabel('中文', { exact: false }).fill('千里之行，始于足下。')
  await dialog.getByLabel('卡片类型').selectOption('vocabulary')
  await expect(dialog.getByLabel('单词', { exact: false })).toHaveValue('journey')
  await page.route('**/api/v1/notes', route => route.abort())
  await dialog.getByRole('button', { name: '添加', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await expect(dialog.getByLabel('单词', { exact: false })).toHaveValue('journey')
  await page.unroute('**/api/v1/notes')
  await dialog.getByRole('button', { name: '添加', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.content-card')).toHaveCount(2)
  await page.getByRole('button', { name: '添加卡片', exact: true }).first().click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('卡片类型').selectOption('sentence')
  await expect(dialog.getByLabel('英文', { exact: false })).toHaveValue('Every journey begins with a single step.')
  await expect(dialog.locator('.template-chip')).toHaveText(['翻译'])
  await expect(dialog.getByText('复述：还需参考音频', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '添加', exact: true }).click()
  await expect(page.locator('.content-card')).toHaveCount(3)
  await page.reload()
  await page.getByRole('button', { name: new RegExp(deck) }).click()
  await expect(page.locator('.content-card')).toHaveCount(3)
  // Refresh drops in-memory CSRF; the next write must refresh it successfully.
  await page.getByRole('button', { name: '添加牌组', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('新牌组名称').fill(deck)
  await dialog.getByRole('button', { name: '添加', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('名称已存在，请换一个名字。')
  await dialog.getByRole('button', { name: '取消' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '添加卡片', exact: true }).first().click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('归属牌组')).toHaveValue(deckId)
  await expect(dialog.getByLabel('卡片类型')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.waitForTimeout(400)
  await page.screenshot({ animations: 'disabled', path: '/tmp/langear-resource-mobile.png', fullPage: true })
  await dialog.getByRole('button', { name: '取消' }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: '添加卡片', exact: true }).first().click()
  await page.getByRole('dialog').getByLabel('卡片类型').selectOption('sentence')
  await page.waitForTimeout(400)
  await page.screenshot({ animations: 'disabled', path: '/tmp/langear-resource-desktop.png', fullPage: true })
  await page.getByRole('dialog').getByRole('button', { name: '取消' }).click()
  expect(errors).toEqual([])
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录 LanGear' })).toBeVisible()
})
